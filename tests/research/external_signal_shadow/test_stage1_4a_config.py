    EXTERNAL_SIGNAL_STAGE1_4_FUNDING_SETTLEMENT_COVERAGE_MIN_RATIO,
    EXTERNAL_SIGNAL_STAGE1_4_HISTORY_DAYS_MIN,
    EXTERNAL_SIGNAL_STAGE1_4_HISTORY_DAYS_PREFERRED,
